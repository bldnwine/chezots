const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const source = fs.readFileSync(require('path').join(__dirname, '../Palette.js'), 'utf8').replace(/^\.pragma library\s*/, '');
const context = vm.createContext({});
vm.runInContext(source + '\nthis.api = {parse, complete, decode, validColor, qmlColor};', context);
const p = context.api;
assert.strictEqual(p.qmlColor('#11223344'), '#44112233');
assert.strictEqual(p.qmlColor('#112233'), '#112233');
assert(!p.validColor('#fff'));
assert(!p.validColor('#11223344aa'));
assert.strictEqual(p.parse('background = "#abcdef"\nforeground = "bad"').paper, '#abcdef');
assert.strictEqual(p.parse('background = "#abcdef"\nforeground = "bad"').ink, undefined);
const base = {paper:'#123456',ink:'#aabbcc',inkDeep:'#112233',sumi:'#223344',indigo:'#334455',green:'#445566',sealRaw:'#556677'};
const full = p.complete(base);
assert.strictEqual(full.bg, '#123456f0');
assert.strictEqual(full.sep, '#aabbcc2e');
assert.strictEqual(full.rowHi, '#aabbcc0f');
assert.strictEqual(full.rowSel, '#5566772e');
assert.strictEqual(p.complete({...base, bg:'#11223344'}).bg, '#11223344');
assert.strictEqual(p.decode(JSON.stringify({version:1, revision:'r1', colors:full})).revision, 'r1');
assert.throws(() => p.decode(JSON.stringify({version:2, colors:full})));
assert.throws(() => p.decode(JSON.stringify({version:1, colors:base})));
console.log('palette tests passed');
