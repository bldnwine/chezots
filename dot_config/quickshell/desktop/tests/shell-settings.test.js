const assert = require('assert');
const model = require('../ShellSettingsModel.js');
assert.deepStrictEqual(model.normalize(model.initial()), model.initial());
assert.throws(() => model.normalize({version: 2, settings: {}}));
assert.throws(() => model.normalize({version: 1, settings: null}));
const values = model.settings({panelScale: 20, locusScale: 0, panelTextScale: NaN, locusTextScale: .1, normalWidth: -1, locusHeight: 0});
assert.strictEqual(values.panelScale, 1.5);
assert.strictEqual(values.locusScale, .75);
assert.strictEqual(values.panelTextScale, 1);
assert.strictEqual(values.locusTextScale, .7);
assert.strictEqual(values.normalWidth, 480);
assert.strictEqual(values.locusHeight, 0);
assert.deepStrictEqual(model.sectionKeys('panels'), ['panelScale', 'panelTextScale', 'panelOpacity', 'panelBlur']);
assert(!model.sectionKeys('locus').includes('windowWidth'));
const legacy = model.normalize({version: 1, settings: {panelScale: 1.1}}).settings;
assert.strictEqual(legacy.panelOpacity, null);
assert.strictEqual(legacy.locusOpacity, null);
assert.strictEqual(legacy.panelBlur, false);
assert.strictEqual(legacy.locusBlur, false);
const effects = model.settings({panelOpacity: .375, locusOpacity: 1.9, panelBlur: true, locusBlur: 'true'});
assert.strictEqual(effects.panelOpacity, .375);
assert.strictEqual(effects.locusOpacity, 1);
assert.strictEqual(effects.panelBlur, true);
assert.strictEqual(effects.locusBlur, false);
assert.strictEqual(model.settings({panelOpacity: -1}).panelOpacity, 0);
for (const invalid of [null, NaN, Infinity, '0.5']) assert.strictEqual(model.settings({panelOpacity: invalid}).panelOpacity, null);
assert.strictEqual(model.normalize(JSON.parse(JSON.stringify({version: 1, settings: effects}))).settings.panelOpacity, .375);
assert(!model.sectionKeys('panels').includes('locusOpacity'));
assert(!model.sectionKeys('locus').includes('panelBlur'));
assert(model.sectionKeys('locus').includes('locusOpacity'));
assert(model.sectionKeys('locus').includes('locusBlur'));
console.log('shell settings model tests passed');
