#!/usr/bin/env python3
"""Cache bar SVG ink bounds for QML; regeneration requires PySide6."""
import argparse
import json
import math
from pathlib import Path
import xml.etree.ElementTree as ET

from PySide6.QtCore import QByteArray, QRectF
from PySide6.QtSvg import QSvgRenderer


desktop = Path(__file__).resolve().parents[1]
folder = desktop / "icons/bar"
destination = desktop / "BarIconMetrics.js"


def bounds(filename):
    svg = ET.fromstring(filename.read_bytes())
    view = [float(value) for value in svg.attrib["viewBox"].replace(",", " ").split()]
    if (len(view) != 4 or not all(math.isfinite(value) for value in view)
            or view[2] <= 0 or view[2] != view[3]):
        raise ValueError(f"Expected a positive square viewBox in {filename}")
    group = ET.Element("{http://www.w3.org/2000/svg}g", {"id": "artwork"})
    for element in list(svg):
        svg.remove(element)
        group.append(element)
    svg.append(group)
    renderer = QSvgRenderer(QByteArray(ET.tostring(svg)))
    rectangle = renderer.boundsOnElement("artwork")
    if (not renderer.isValid() or rectangle.isEmpty()
            or not all(math.isfinite(value) for value in
                       (rectangle.x(), rectangle.y(), rectangle.width(), rectangle.height()))):
        raise ValueError(f"Cannot measure {filename}")
    return QRectF((rectangle.x() - view[0]) / view[2],
                  (rectangle.y() - view[1]) / view[3],
                  rectangle.width() / view[2], rectangle.height() / view[3])


def family(name):
    for prefix in ("network-wireless-", "bluetooth-", "audio-volume-", "battery-level-"):
        if name.startswith(prefix):
            return prefix
    if name in ("notifications", "notifications_off"):
        return "notifications"
    if name in ("cloud", "cloud_off"):
        return "cloud"
    return name


measured = {path.stem: bounds(path) for path in sorted(folder.glob("*.svg"))}
groups = {}
for name, rectangle in measured.items():
    key = family(name)
    groups[key] = groups[key].united(rectangle) if key in groups else rectangle

table = {name: [round(value, 9) for value in
                (groups[family(name)].x(), groups[family(name)].y(),
                 groups[family(name)].width(), groups[family(name)].height())]
         for name in measured}
output = """// Generated by scripts/bar-icon-metrics.py from the bundled SVGs.
// Bounds are fractions of the original viewBox: x, y, width, height.
var inkBounds = """ + json.dumps(table, indent=4) + """;

function bounds(name) {
    return inkBounds[name] || [0, 0, 1, 1];
}

if (typeof module !== "undefined") module.exports = { bounds, inkBounds };
"""
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true", help="Check without writing")
args = parser.parse_args()
if args.check:
    if not destination.exists() or destination.read_text() != output:
        raise SystemExit("BarIconMetrics.js differs from the bundled SVG geometry")
    print(f"Verified bounds for {len(table)} bar icons")
else:
    destination.write_text(output)
    print(f"Cached bounds for {len(table)} bar icons")
