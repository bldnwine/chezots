#!/usr/bin/env python3
"""Cache SVG ink bounds for QML; requires PySide6 only when regenerating."""
import argparse
import json
from pathlib import Path
import xml.etree.ElementTree as ET

from PySide6.QtCore import QByteArray, QRectF
from PySide6.QtSvg import QSvgRenderer

desktop = Path(__file__).resolve().parents[1]
folder = desktop / "icons/material-rounded"
destination = desktop / "MaterialMetrics.js"


def bounds(filename):
    svg = ET.fromstring(filename.read_bytes())
    view = [float(value) for value in svg.attrib["viewBox"].split()]
    group = ET.Element("{http://www.w3.org/2000/svg}g", {"id": "artwork"})
    for element in list(svg):
        svg.remove(element)
        group.append(element)
    svg.append(group)
    renderer = QSvgRenderer(QByteArray(ET.tostring(svg)))
    rectangle = renderer.boundsOnElement("artwork")
    if not renderer.isValid() or rectangle.isEmpty():
        raise ValueError(f"Cannot measure {filename}")
    return QRectF((rectangle.x() - view[0]) / view[2],
                  (rectangle.y() - view[1]) / view[3],
                  rectangle.width() / view[2], rectangle.height() / view[3])


names = sorted(path.name.removesuffix("_20px.svg")
               for path in folder.glob("*_20px.svg") if "_fill1_" not in path.name)
measured = {}
for name in names:
    measured[name] = bounds(folder / f"{name}_20px.svg").united(
        bounds(folder / f"{name}_fill1_20px.svg"))

# Signal levels intentionally remove arcs. Keep their scale and position stable.
for name in ("wifi_1_bar", "wifi_2_bar"):
    measured[name] = measured["wifi"]

table = {name: [round(value, 9) for value in
               (rectangle.x(), rectangle.y(), rectangle.width(), rectangle.height())]
         for name, rectangle in measured.items()}
output = """// Generated by scripts/material-icon-metrics.py from the bundled SVGs.
// Bounds are fractions of the original viewBox: x, y, width, height.
var inkBounds = """ + json.dumps(table, indent=4) + """;

function bounds(name) {
    return inkBounds[name] || [0, 0, 1, 1];
}

if (typeof module !== "undefined") module.exports = { bounds, inkBounds };
"""
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true", help="Check without writing")
args = parser.parse_args()
if args.check:
    if destination.read_text() != output:
        raise SystemExit("MaterialMetrics.js differs from the bundled SVG geometry")
    print(f"Verified bounds for {len(table)} symbols and both fill states")
else:
    destination.write_text(output)
    print(f"Cached bounds for {len(table)} symbols and both fill states")
